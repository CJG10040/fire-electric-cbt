    by_k = {k: [] for k in known}
    seen = set()
    for n in NOTES:
        assert n['id'] not in seen
        seen.add(n['id'])
        assert n['status'] in {'amendment','correction','supplement','checked','pending'}
        assert n['ks'] and len(n['ks']) == len(set(n['ks']))
        assert n['refs'] and n['lines']
        for r in n['refs']:
            assert r['source'] in SOURCES and r['provision']
        for k in n['ks']:
            assert k in known, (n['id'],k)
            by_k[k].append(n['id'])
    tech = set(TECHNICAL) | {c['k'] for c in clusters if c['tp'] == 12}
    assert tech <= known, sorted(tech-known)
    review = {}
    for c in clusters:
        k = c['k']
        if by_k[k]:
            ns = [n for n in NOTES if n['id'] in by_k[k]]
            status = next((s for s in ['pending','amendment','correction','supplement','checked'] if any(n['status']==s for n in ns)))
            review[k] = dict(status=status, notes=by_k[k])
        elif k in tech:
            review[k] = dict(status='technical', notes=[], reason='일반이론·제품 또는 도면 조건에 관한 문항으로 분류했습니다. 법령 개정으로 답을 교체하지 않았으며 원문 정답의 정확성을 보증하는 표시는 아닙니다.')
